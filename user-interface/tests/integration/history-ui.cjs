const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require('playwright');
const root = path.resolve(__dirname, '../../..');
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? {executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH} : {}) });
  try {
    const page = await browser.newPage({ viewport: {width:390,height:844}, timezoneId:'America/Vancouver', hasTouch:true });
    page.setDefaultTimeout(10000);
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    const historyQueries=[];page.on('request',request=>{if(request.url().includes('/electrical/history?'))historyQueries.push(new URL(request.url()));});
    await page.clock.install({fixedTime:new Date('2026-10-28T22:00:00Z')});
    await page.goto('http://127.0.0.1:18081/elec/history');
    await page.getByText('SIMULATED DATA · Windows BMV simulator',{exact:true}).waitFor();
    await page.getByText('RECORDED RANGE',{exact:true}).waitFor();
    assert(await page.getByRole('button',{name:'Later ›',exact:true}).isDisabled());
    const raw=await (await fetch('http://127.0.0.1:18787/electrical/history?start=1793170800000&end=1793257200000')).json();
    assert.equal((await fetch('http://127.0.0.1:18787/electrical/history?start=1&end=0')).status,400);
    assert.equal(raw.source,'simulated');assert(raw.points.length>0 && raw.points.length<8192);
    assert.equal(new Set(raw.points.map(p=>p[6])).size,2);
    console.log('History loaded from SQLite; checking chart inspection');
    // The chart retains extrema and does not join across the one-hour gap.
    const chart=page.getByRole('button',{name:/Charge level history chart/});
    assert.equal(await chart.locator('path').count(),2);
    await chart.click({position:{x:150,y:100}});
    await page.getByRole('button',{name:'Previous reading',exact:true}).click();
    await page.setViewportSize({width:390,height:1500});
    await page.getByText('Historical Usage',{exact:true}).scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(root,'docs/images/battery-history-implemented.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    console.log('Checking pinch zoom, button increments, panning and finer SQLite resolution');
    const cdp=await page.context().newCDPSession(page);
    const ready=async(label)=>{
      await page.waitForFunction(expected=>document.querySelector('[data-testid="history-window-duration"]')?.textContent===expected,label);
      await page.getByRole('button',{name:'Refresh history',exact:true}).waitFor({state:'visible'});
      await page.waitForFunction(()=>![...document.querySelectorAll('button')].find(b=>b.getAttribute('aria-label')==='Refresh history')?.disabled);
    };
    const lastQuery=()=>historyQueries.at(-1);
    const queryWindow=()=>({start:Number(lastQuery().searchParams.get('start')),end:Number(lastQuery().searchParams.get('end'))});
    const touch=async(type,points)=>cdp.send('Input.dispatchTouchEvent',{type,touchPoints:points.map((p,i)=>({x:p.x,y:p.y,id:i+1}))});
    const pinch=async(outward,{cancel=false,fraction=.5}={})=>{
      const plot=page.getByRole('button',{name:/Charge level history chart/});
      await plot.scrollIntoViewIfNeeded();
      const box=await plot.boundingBox();
      const cx=box.x+box.width*(55+345*fraction)/420,cy=box.y+box.height*.43;
      const initial=outward?30:50,finish=outward?50:30;
      const pair=radius=>[{x:cx-radius,y:cy},{x:cx+radius,y:cy}];
      const before=historyQueries.length;
      await touch('touchStart',[pair(initial)[0]]);
      await touch('touchStart',pair(initial));
      for(let i=1;i<=6;i++)await touch('touchMove',pair(initial+(finish-initial)*i/6));
      assert.equal(historyQueries.length,before,'pinch preview must not query on each move');
      await touch(cancel?'touchCancel':'touchEnd',[]);
    };
    await ready('24 hours');
    await page.getByRole('button',{name:'Zoom in',exact:true}).click();await ready('23 hours');
    await chart.scrollIntoViewIfNeeded();
    const beforeScroll=await page.getByTestId('battery-history-scroll').evaluate(node=>node.scrollTop);
    const scrollBox=await chart.boundingBox();
    const sx=scrollBox.x+scrollBox.width*.6,sy=scrollBox.y+scrollBox.height*.5;
    const beforeVertical=historyQueries.length;
    await touch('touchStart',[{x:sx,y:sy}]);
    for(let i=1;i<=5;i++){await touch('touchMove',[{x:sx,y:sy-i*18}]);await page.waitForTimeout(30);}
    await touch('touchEnd',[]);
    await page.waitForFunction(before=>document.querySelector('[data-testid="battery-history-scroll"]').scrollTop>before,beforeScroll);
    assert.equal(historyQueries.length,beforeVertical,'vertical page scrolling must not pan or query');
    await ready('23 hours');
    await page.getByRole('button',{name:'Reset zoom',exact:true}).click();await ready('24 hours');
    await pinch(true);await ready('12 hours');
    assert.equal(queryWindow().end-queryWindow().start,12*3600000);
    await pinch(true);await ready('6 hours');
    await pinch(true);await ready('3 hours');
    await pinch(false);await ready('6 hours');
    const beforeCancel=historyQueries.length;
    await pinch(true,{cancel:true});await ready('6 hours');
    assert.equal(historyQueries.length,beforeCancel,'cancelled gestures must not commit');
    // Dragging right reveals earlier time without changing the width.
    const beforePan=queryWindow();
    await chart.scrollIntoViewIfNeeded();
    const panBox=await chart.boundingBox(),panX=panBox.x+panBox.width*.5,panY=panBox.y+panBox.height*.4;
    await touch('touchStart',[{x:panX,y:panY}]);
    for(let i=1;i<=6;i++)await touch('touchMove',[{x:panX+i*8,y:panY}]);
    await touch('touchEnd',[]);
    await page.waitForFunction(()=>!document.querySelector('[role="progressbar"]'));
    await ready('6 hours');
    assert(queryWindow().start<beforePan.start,'drag right must pan earlier');
    assert.equal(queryWindow().end-queryWindow().start,6*3600000);
    await page.getByRole('button',{name:'Zoom in',exact:true}).click();await ready('5 hours');
    await page.getByRole('button',{name:'Zoom out',exact:true}).click();await ready('6 hours');
    for(const label of ['3 hours','1 h 30 min','45 minutes','22 min 30 s','11 min 15 s','5 min 38 s','5 minutes']){
      await pinch(true);await ready(label);
    }
    assert(await page.getByRole('button',{name:'Zoom in',exact:true}).isDisabled());
    const fine=queryWindow();
    const fineResult=await(await fetch(lastQuery().toString())).json();
    const originalInWindow=raw.points.filter(p=>p[0]>=fine.start&&p[0]<fine.end).length;
    assert(fineResult.points.length>originalInWindow,'zoom must retrieve finer samples, not stretch coarse chart data');
    assert.equal(fine.end-fine.start,5*60000);
    const selectedLabel=()=>page.getByText(/^Selected reading ·/).innerText();
    const selectedBefore=await selectedLabel();
    assert(/\d{1,2}:\d{2}:\d{2}/.test(selectedBefore),'fine windows must expose seconds');
    await page.getByRole('button',{name:'Next reading',exact:true}).click();
    assert.notEqual(await selectedLabel(),selectedBefore,'fine sample inspection must distinguish packet times');
    await page.setViewportSize({width:390,height:1650});
    await page.getByText('Historical Usage',{exact:true}).scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(root,'docs/images/battery-history-zoom.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button',{name:'Pan earlier',exact:true}).click();await ready('5 minutes');
    await page.getByRole('button',{name:'Pan later',exact:true}).click();await ready('5 minutes');
    await page.getByRole('button',{name:'Zoom out',exact:true}).click();await ready('10 minutes');
    await page.getByRole('button',{name:'Reset zoom',exact:true}).click();await ready('24 hours');
    assert(await page.getByRole('button',{name:'Reset zoom',exact:true}).isDisabled());
    // Pinch into a recording gap, then recover using a reverse pinch on the empty chart.
    for(const label of ['12 hours','6 hours','3 hours','1 h 30 min','45 minutes']){
      await pinch(true,{fraction:8.5/24});await ready(label);
    }
    await page.getByText('No readings recorded',{exact:true}).waitFor();
    await pinch(false,{fraction:8.5/24});await ready('1 h 30 min');
    await page.getByText('VISIBLE RANGE',{exact:true}).waitFor();
    assert.equal(await page.getByText('No readings recorded',{exact:true}).count(),0);
    await page.getByRole('button',{name:'Reset zoom',exact:true}).click();await ready('24 hours');
    console.log('Zoom gestures/controls, scrolling, empty-chart recovery and finer history query checks passed');
    console.log('Inspection passed; checking metrics and date ranges');
    await page.getByRole('button',{name:'Current',exact:true}).click();
    assert(await page.getByText('Charge level',{exact:true}).count()===0);
    await page.getByRole('button',{name:'Starter',exact:true}).click();
    await page.getByText('Why voltage only?',{exact:true}).waitFor();
    await page.setViewportSize({width:390,height:1500});
    await page.getByText('Historical Usage',{exact:true}).scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(root,'docs/images/battery-history-starter-implemented.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.getByRole('button',{name:'Charge',exact:true}).count(),0);
    assert((await page.locator('body').innerText()).includes('Starter charge and current are unavailable.'));
    await page.getByRole('button',{name:'7 days',exact:true}).click();
    await page.getByText('RECORDED RANGE',{exact:true}).waitFor();
    await page.getByRole('button',{name:'30 days',exact:true}).click();
    await page.getByText('RECORDED RANGE',{exact:true}).waitFor();
    await page.getByRole('button',{name:'24 hours',exact:true}).click();
    await page.getByRole('button',{name:'‹ Earlier',exact:true}).click();
    await page.getByText('No starter voltage recorded',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Later ›',exact:true}).click();
    await page.getByText('RECORDED RANGE',{exact:true}).waitFor();
    console.log('Ranges and empty state passed; checking failure/retry');
    await page.route('**/electrical/history?*',route=>route.fulfill({status:503,body:'{}'}));
    await page.getByRole('button',{name:'Refresh history',exact:true}).click();
    await page.getByRole('alert').waitFor();
    assert.equal(await page.getByText('RECORDED RANGE',{exact:true}).count(),0);
    assert(!(await page.locator('body').innerText()).includes('ILLUSTRATIVE DEMO'));
    await page.unroute('**/electrical/history?*');
    await page.getByRole('button',{name:'Retry',exact:true}).click();
    await page.getByText('RECORDED RANGE',{exact:true}).waitFor();
    await page.reload();
    await page.getByText('RECORDED RANGE',{exact:true}).waitFor();
    // Tablet width and app dark appearance use the same history component.
    await page.setViewportSize({width:1024,height:900});
    await page.getByRole('button',{name:/Boat profile:/}).click();
    await page.getByRole('button',{name:'Settings → Choose a white or black background'}).click();
    await page.getByRole('radio',{name:/Black/}).click();
    await page.getByRole('button',{name:'Save',exact:true}).click();
    await page.getByText('RECORDED RANGE',{exact:true}).waitFor();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
    await pinch(true);await ready('12 hours');
    await page.getByRole('button',{name:'Reset zoom',exact:true}).click();await ready('24 hours');
    assert.deepEqual(errors,[]);
    console.log('History SQLite/service/UI: chart gaps, inspection, metrics, battery/ranges, empty/error/retry, reload and appearance pass');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exit(1);});
